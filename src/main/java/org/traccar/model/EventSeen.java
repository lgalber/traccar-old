package org.traccar.model;

import org.traccar.storage.StorageName;

import java.util.Date;

/**
 * Marks an event as seen by a user, so it no longer appears in that user's pending alerts.
 */
@StorageName("tc_events_seen")
public class EventSeen extends BaseModel {

    private long userId;

    public long getUserId() {
        return userId;
    }

    public void setUserId(long userId) {
        this.userId = userId;
    }

    private long eventId;

    public long getEventId() {
        return eventId;
    }

    public void setEventId(long eventId) {
        this.eventId = eventId;
    }

    private Date seenTime;

    public Date getSeenTime() {
        return seenTime;
    }

    public void setSeenTime(Date seenTime) {
        this.seenTime = seenTime;
    }

}
